void gfx_init(void) {
    /* VGA mode switch removed for UEFI 64-bit */

    /* Map VGA memory into our page tables */
    for (uint32_t addr = 0xA0000; addr < 0xC0000; addr += PAGE_SIZE) {
        paging_map(addr, addr, PAGE_PRESENT | PAGE_WRITE);
    }

    gfx_active = true;
    gfx_clear(GFX_BLACK);
}

void gfx_exit(void) {
    /* VGA text mode switch removed for UEFI 64-bit */
    gfx_active = false;
}

void gfx_clear(uint8_t color) {
    memset(vram, color, GFX_WIDTH * GFX_HEIGHT);
}

void gfx_putpixel(int x, int y, uint8_t color) {
    if (x < 0 || x >= GFX_WIDTH || y < 0 || y >= GFX_HEIGHT)
        return;
    vram[y * GFX_WIDTH + x] = color;
}

uint8_t gfx_getpixel(int x, int y) {
    if (x < 0 || x >= GFX_WIDTH || y < 0 || y >= GFX_HEIGHT)
        return 0;
    return vram[y * GFX_WIDTH + x];
}

/* Bresenham's line algorithm */
void gfx_draw_line(int x0, int y0, int x1, int y1, uint8_t color) {
    int dx = x1 - x0;
    int dy = y1 - y0;
    int sx = (dx > 0) ? 1 : -1;
    int sy = (dy > 0) ? 1 : -1;
    if (dx < 0) dx = -dx;
    if (dy < 0) dy = -dy;

    int err = dx - dy;

    while (1) {
        gfx_putpixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;

        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 <  dx) { err += dx; y0 += sy; }
    }
}

void gfx_draw_rect(int x, int y, int w, int h, uint8_t color) {
    gfx_draw_line(x, y, x + w - 1, y, color);
    gfx_draw_line(x + w - 1, y, x + w - 1, y + h - 1, color);
    gfx_draw_line(x + w - 1, y + h - 1, x, y + h - 1, color);
    gfx_draw_line(x, y + h - 1, x, y, color);
}

void gfx_fill_rect(int x, int y, int w, int h, uint8_t color) {
    for (int row = y; row < y + h && row < GFX_HEIGHT; row++) {
        if (row < 0) continue;
        int start = MAX(x, 0);
        int end = MIN(x + w, GFX_WIDTH);
        memset(&vram[row * GFX_WIDTH + start], color, end - start);
    }
}

/* Midpoint circle algorithm */
void gfx_draw_circle(int cx, int cy, int r, uint8_t color) {
    int x = r, y = 0, err = 1 - r;
    while (x >= y) {
        gfx_putpixel(cx + x, cy + y, color);
        gfx_putpixel(cx - x, cy + y, color);
        gfx_putpixel(cx + x, cy - y, color);
        gfx_putpixel(cx - x, cy - y, color);
        gfx_putpixel(cx + y, cy + x, color);
        gfx_putpixel(cx - y, cy + x, color);
        gfx_putpixel(cx + y, cy - x, color);
        gfx_putpixel(cx - y, cy - x, color);
        y++;
        if (err < 0) {
            err += 2 * y + 1;
        } else {
            x--;
            err += 2 * (y - x) + 1;
        }
    }
}

void gfx_fill_circle(int cx, int cy, int r, uint8_t color) {
    for (int y = -r; y <= r; y++) {
        int x = 0;
        while (x * x + y * y <= r * r) x++;
        gfx_draw_line(cx - x, cy + y, cx + x, cy + y, color);
    }
}

void gfx_draw_char(int x, int y, char c, uint8_t fg, uint8_t bg) {
    unsigned char uc = (unsigned char)c;
    if (uc < 32 || uc > 127) c = '?';
    const uint8_t *glyph = font_8x8[uc - 32];

    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            uint8_t color = (bits & (0x80 >> col)) ? fg : bg;
            gfx_putpixel(x + col, y + row, color);
        }
    }
}

void gfx_draw_string(int x, int y, const char *str, uint8_t fg) {
    int cx = x;
    while (*str) {
        if (*str == '\n') {
            cx = x;
            y += 10;
        } else {
            gfx_draw_char(cx, y, *str, fg, GFX_BLACK);
            cx += 9;
        }
        str++;
    }
}

void gfx_set_palette(uint8_t index, uint8_t r, uint8_t g, uint8_t b) {
    outb(0x3C8, index);
    outb(0x3C9, r >> 2);   /* VGA uses 6-bit color */
    outb(0x3C9, g >> 2);
    outb(0x3C9, b >> 2);
}

void gfx_vsync(void) {
    /* Wait for vertical retrace */
    while (inb(0x3DA) & 0x08);
    while (!(inb(0x3DA) & 0x08));
}

